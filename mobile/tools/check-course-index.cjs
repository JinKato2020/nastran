const assert=require('node:assert/strict');
const bundle=require('../src/generated/lessons.json');
const {BUNDLED_INDEX,courseIndexFromHTML,isRetired}=require('../src/course-index.ts');
const {titleFor}=require('../src/content.ts');
const {freeAnalysisRoutes,canOpenLesson}=require('../src/pro-access.ts');
const html=data=>'<script>window.NASTRAN_LEARNING = '+JSON.stringify(data)+';</script>';
const index=courseIndexFromHTML(bundle.pages['index.html']);
assert.notEqual(index,BUNDLED_INDEX,'the shipped OTA index must pass the reader validation');
assert.deepEqual(index.navigation,bundle.course.navigation);
assert.deepEqual(index.materialChapters,bundle.course.materialChapters);
// Older OTA readers start with 'elements' selected. Keep it as a navigation source only.
assert(!index.materialChapters.some(chapter=>chapter.key==='elements'),'the shipped index must open with every chapter collapsed on older readers');
assert.deepEqual(index.home,bundle.course.home);
assert.deepEqual(index.analysisHeadings,bundle.course.analysisHeadings);
assert.deepEqual(index.retiredLinks,bundle.course.retiredLinks);
if(index.home.hero.image)assert(index.heroArt?.startsWith('data:image/'));
const next=structuredClone(bundle.course);
const topic={path:'theory.html',hash:'#qa',title:'Added',description:'OTA'};
next.navigation.newTheory=[topic];
next.materialChapters=[{key:'qa',title:'New',description:'Added by release',sources:['newTheory']}];
next.navigation.analyses=[{...topic,path:'analysis.html',group:'構造・静解析'}];
next.navigation.homeResources=[];
next.retiredLinks=['elements.html#old'];
next.home.sections=[{key:'qa-list',style:'list',title:'Added',items:[topic]}];
next.home.layouts.blueprint=['qa-list','hero'];
const updated=courseIndexFromHTML(html(next));
assert.deepEqual(updated.navigation.newTheory,[topic]);
assert.deepEqual(updated.materialChapters,next.materialChapters);
assert.equal(titleFor({...topic,y:0},updated),'Added');
assert(canOpenLesson(next.navigation.analyses[0],false,freeAnalysisRoutes(updated.navigation.analyses)));
assert(isRetired(updated,{path:'elements.html',hash:'#old/section'}));
assert(!isRetired(updated,{path:'elements.html',hash:'#older'}));
for(const invalid of [null,{...next,home:{...next.home,layouts:{blueprint:['unknown']}}},{...next,materialChapters:[{...next.materialChapters[0],sources:['missing']}]},
 {...next,navigation:{...next.navigation,newTheory:[{...topic,path:'external.html'}]}}])assert.equal(courseIndexFromHTML(html(invalid)),BUNDLED_INDEX);
const legacy={navigation:{...bundle.course.navigation}};
delete legacy.navigation.meshTheory;
const restored=courseIndexFromHTML(html(legacy));
assert(!restored.materialChapters.some(chapter=>chapter.key==='meshTheory'));
assert.equal(courseIndexFromHTML(),BUNDLED_INDEX);
console.log('PASS: shipped curriculum, new/removed chapters, routes, archived releases, home layouts, images and invalid-index fallback.');
